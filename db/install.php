/**
 * Point the app's remote CSS at this plugin on install, unless the site already set its own.
 *
 * @return bool
 */
function xmldb_local_oksigeniaaty_install(): bool {
    global $CFG;
    require_once($CFG->dirroot . '/local/oksigeniaaty/lib.php');
    local_oksigeniaaty_refresh_appcss();
    return true;
}
